/// Finds `name` in one arity table.
fn php_arity_override(
    name: &str,
    table: &'static [(&'static str, EvalBuiltinArity)],
) -> Option<EvalBuiltinArity> {
    table.iter().find(|(entry, _)| *entry == name).map(|(_, arity)| *arity)
}

/// Returns the canonical PHP name and arity of a builtin reachable by `name`, if any.
///
/// Language constructs (`isset`, `exit`, ...) are not functions to PHP and answer `None`, as
/// does any name the active runtime hides (strict-PHP extensions, a missing regex provider).
pub(in crate::interpreter) fn eval_builtin_call_arity(
    name: &str,
) -> Option<(&'static str, EvalBuiltinArity)> {
    if let Some(spec) = eval_declared_builtin_spec(name) {
        return (!spec.is_language_construct()).then_some((spec.name, spec.php_arity()));
    }
    let key = name.trim_start_matches('\\').to_ascii_lowercase();
    OPCACHE_ARITY
        .iter()
        .find(|(entry, _)| *entry == key)
        .map(|(entry, arity)| (*entry, *arity))
}

/// Throws PHP's `ArgumentCountError` when `supplied` evaluated arguments are refused.
pub(in crate::interpreter) fn eval_check_builtin_arity(
    name: &str,
    supplied: usize,
    context: &mut ElephcEvalContext,
    values: &mut impl RuntimeValueOps,
) -> Result<(), EvalStatus> {
    if eval_opcache_is_user_function(name, context) {
        return Ok(());
    }
    let Some((canonical, arity)) = eval_builtin_call_arity(name) else {
        return Ok(());
    };
    match arity.refusal(canonical, supplied) {
        Some(message) => eval_throw_argument_count_error(&message, context, values),
        None => Ok(()),
    }
}

/// Checks a direct positional builtin call before any specialised handler sees its arguments.
///
/// A refused call still evaluates every argument in source order, then releases it, before the
/// error is thrown. A plain variable in a by-reference slot is skipped: PHP binds it without
/// reading it, so reading it here would emit an `Undefined variable` warning PHP does not.
/// Calls with named or spread arguments are left to `eval_check_builtin_arity` once bound.
pub(in crate::interpreter) fn eval_check_builtin_source_arity(
    name: &str,
    args: &[EvalCallArg],
    context: &mut ElephcEvalContext,
    scope: &mut ElephcEvalScope,
    values: &mut impl RuntimeValueOps,
) -> Result<(), EvalStatus> {
    if eval_opcache_is_user_function(name, context) || !eval_call_args_are_plain_positional(args) {
        return Ok(());
    }
    let Some((canonical, arity)) = eval_builtin_call_arity(name) else {
        return Ok(());
    };
    let Some(message) = arity.refusal(canonical, args.len()) else {
        return Ok(());
    };
    let spec = eval_declared_builtin_spec(name);
    let evaluated = args
        .iter()
        .enumerate()
        .filter(|(position, arg)| {
            let by_ref = spec.is_some_and(|spec| spec.param_is_by_ref(*position));
            !(by_ref && matches!(arg.value(), EvalExpr::LoadVar(_)))
        })
        .map(|(_, arg)| arg.value())
        .collect::<Vec<_>>();
    with_eval_void_operands(&evaluated, context, scope, values, |_, context, _, values| {
        eval_throw_argument_count_error(&message, context, values)
    })
}
