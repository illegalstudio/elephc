//! Purpose:
//! PHP's argument-count contract for builtin calls made from eval: the accepted range, the
//! `ArgumentCountError` message, and the two checks that raise it before any handler runs.
//!
//! Called from:
//! - `crate::interpreter::expressions::calls::eval_call()` for direct source calls.
//! - `crate::interpreter::builtins::registry::dispatch` and callable dispatch for evaluated
//!   arguments (`call_user_func`, `call_user_func_array`, `$f()`, spread calls, callbacks).
//!
//! Key details:
//! - The range is the eval signature's (required parameters, fixed parameters, variadic), except
//!   for the builtins in `PHP_ARITY_OVERRIDES`. Their eval signature lists fewer parameters than
//!   PHP 8.5 declares (`array_keys` stops at `$array`, `mktime` marks all six required), and a
//!   check driven by it would refuse calls PHP accepts. The table was generated by comparing
//!   every registry builtin against `ReflectionFunction` on PHP 8.5, then every refused count
//!   was replayed there to pin the exact message (1216 calls, all matching).
//! - Older profiles only differ by trailing optional parameters PHP added later (`fputcsv`'s
//!   `$eol` is 8.1), so they accept a few counts reference PHP would refuse; they never refuse
//!   one it accepts.
//! - A handler that does not implement every count PHP accepts keeps its own `RuntimeFatal`
//!   check: this module only answers the counts PHP itself refuses.
//! - A direct call evaluates its arguments before raising, as PHP sends them first.

use super::super::super::*;

/// How PHP words a refused argument count for one builtin.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(in crate::interpreter) enum EvalArityWording {
    /// `exactly` when the range is one count, else `at least` / `at most`.
    Ranged,
    /// `exactly <violated bound>` for either side (`strtr`, `pcntl_setqos_class`).
    Exact,
    /// Zero arguments, or exactly `min`; any other count reads `exactly <min>` (`rand`).
    ZeroOrExact,
}

/// The argument counts PHP accepts for one builtin, plus its refusal wording.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(in crate::interpreter) struct EvalBuiltinArity {
    /// Fewest arguments accepted.
    pub(in crate::interpreter) min: usize,
    /// Most arguments accepted; `None` for a variadic builtin.
    pub(in crate::interpreter) max: Option<usize>,
    /// Message shape for a refused count.
    pub(in crate::interpreter) wording: EvalArityWording,
}

impl EvalBuiltinArity {
    /// Builds the ordinary range PHP's parameter parser enforces.
    pub(in crate::interpreter) const fn ranged(min: usize, max: Option<usize>) -> Self {
        Self { min, max, wording: EvalArityWording::Ranged }
    }

    /// Builds a range whose refusal always reads `exactly <violated bound>`.
    const fn exact(min: usize, max: usize) -> Self {
        Self { min, max: Some(max), wording: EvalArityWording::Exact }
    }

    /// Builds the `rand()` shape: no arguments, or exactly `count` of them.
    const fn zero_or_exactly(count: usize) -> Self {
        Self { min: count, max: Some(count), wording: EvalArityWording::ZeroOrExact }
    }

    /// Returns the arity for one registry builtin from its eval signature and the PHP table.
    pub(in crate::interpreter) fn for_signature(
        name: &str,
        required: usize,
        fixed: usize,
        variadic: bool,
    ) -> Self {
        php_arity_override(name, PHP_ARITY_OVERRIDES).unwrap_or_else(|| {
            Self::ranged(required, (!variadic).then_some(fixed))
        })
    }

    /// Returns PHP's `ArgumentCountError` message when `supplied` is refused, else `None`.
    pub(in crate::interpreter) fn refusal(&self, name: &str, supplied: usize) -> Option<String> {
        let too_few = supplied < self.min;
        let too_many = self.max.is_some_and(|max| supplied > max);
        let (kind, bound) = match self.wording {
            EvalArityWording::ZeroOrExact if supplied == 0 || supplied == self.min => return None,
            EvalArityWording::ZeroOrExact => ("exactly", self.min),
            _ if !too_few && !too_many => return None,
            EvalArityWording::Exact if too_few => ("exactly", self.min),
            EvalArityWording::Exact => ("exactly", self.max.unwrap_or(self.min)),
            EvalArityWording::Ranged if self.max == Some(self.min) => ("exactly", self.min),
            EvalArityWording::Ranged if too_few => ("at least", self.min),
            EvalArityWording::Ranged => ("at most", self.max.unwrap_or(self.min)),
        };
        let plural = if bound == 1 { "" } else { "s" };
        Some(format!("{name}() expects {kind} {bound} argument{plural}, {supplied} given"))
    }
}

