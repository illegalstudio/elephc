//! Purpose:
//! Generates the C declarations of the extension ABI from the elephc-zend
//! crate's Rust source.
//!
//! Called from:
//! - `crates/elephc-zend/build.rs` (the crate's own header, for its tests) and
//!   Elephc's `build.rs` (the header it writes for every extension build),
//!   both through `#[path]`, so the two can never disagree.
//!
//! Key details:
//! - Rust is the single source of truth. Every `#[repr(C)]` struct or union,
//!   `pub type` alias and `pub const` under `src/abi/` becomes a C typedef or
//!   `#define`; every `#[no_mangle] extern "C"` function or static anywhere in
//!   `src/` becomes a prototype or `extern` declaration; every function in an
//!   `extern "C"` block under `src/abi/` (the C-defined variadics) is declared
//!   too. The result is the text of `elephc_zend_abi.h`.
//! - What Rust cannot say, doc comments say, one directive per line:
//!   `c: tag <name>` sets a struct's C tag (default `_<name>`); `c: opaque`
//!   declares the type without a body; `c: anonymous` on a union-typed field
//!   inlines that union as an anonymous member; `c: hidden` keeps an exported
//!   item out of the header; `c: enum` on a `c_int` alias makes it a C enum
//!   whose members are the constants declared with that alias as their type
//!   (C++ extensions reuse member names like `SUCCESS` in their own enums,
//!   which a `#define` would clobber); `c: system <spelling>` names a type the C system
//!   headers already declare (`struct stat`, `FILE`), referenced by that
//!   spelling and never redeclared.
//! - The generator only understands the shapes this crate uses; anything else
//!   is a build error naming the item, never silently wrong C.

use std::cell::RefCell;
use std::collections::HashMap;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use syn::{
    Attribute, BinOp, Expr, Fields, FnArg, ForeignItem, GenericArgument, Item, Lit, Pat, PathArguments,
    ReturnType, Type, UnOp,
};

/// ABI definition files, in the order their items are emitted: a struct
/// embedded by value must be defined before the struct embedding it.
const ABI_FILES: &[&str] = &[
    "abi/scalars.rs",
    "abi/values.rs",
    "abi/engine.rs",
    "abi/runtime.rs",
    "abi/c_side.rs",
];

thread_local! {
    /// Rust names of system-declared C types, and their C spelling.
    static SYSTEM: RefCell<HashMap<String, String>> = RefCell::new(HashMap::new());
}


/// One item collected from the Rust source.
enum Decl {
    Const { name: String, ty: Type, value: Expr, doc: String },
    Alias { name: String, ty: Type },
    Enum { name: String, members: Vec<(String, Expr)> },
    Record { name: String, tag: String, union: bool, fields: Vec<Field>, opaque: bool, doc: String },
    Function { text: String },
    Static { text: String },
}

struct Field {
    name: String,
    ty: Type,
    anonymous: bool,
}

/// The header for the crate whose `src/` directory is `src`.
pub fn generate(src: &Path) -> Result<String, String> {
    let mut decls = Vec::new();
    for file in ABI_FILES {
        collect_abi(&src.join(file), &mut decls)?;
    }
    let mut exported = Vec::new();
    collect_exports(src, &mut exported)?;
    exported.sort_by(|a, b| a.0.cmp(&b.0));

    let records: HashMap<String, (bool, Vec<(String, Type)>)> = decls
        .iter()
        .filter_map(|decl| match decl {
            Decl::Record { name, union, fields, .. } => {
                Some((name.clone(), (*union, fields.iter().map(|f| (f.name.clone(), f.ty.clone())).collect())))
            }
            _ => None,
        })
        .collect();

    let mut text = String::from(
        "/* elephc_zend_abi.h — GENERATED by crates/elephc-zend/build.rs from the crate's Rust\n \
         * source. The types, constants and functions of Elephc's PHP extension ABI; the\n \
         * macros extensions expand are in zend_macros.h. Do not edit. */\n\n\
         #ifndef ELEPHC_ZEND_ABI_H\n#define ELEPHC_ZEND_ABI_H\n\n\
         #include <stdint.h>\n#include <stddef.h>\n#include <stdbool.h>\n#include <stdarg.h>\n\
         #include <stdio.h>\n#include <setjmp.h>\n#include <sys/types.h>\n#include <sys/stat.h>\n\
         #include <dirent.h>\n\n\
         #ifdef __cplusplus\nextern \"C\" {\n#endif\n\n",
    );

    text.push_str("/* ------------------------------------------------------------ constants */\n\n");
    for decl in &decls {
        if let Decl::Const { name, ty, value, doc } = decl {
            if !doc.is_empty() {
                let _ = writeln!(text, "/* {doc} */");
            }
            let _ = writeln!(text, "#define {name} {}", const_value(name, ty, value)?);
        }
    }

    text.push_str("\n/* ------------------------------------------------------------ type names */\n\n");
    for decl in &decls {
        if let Decl::Record { name, tag, union, .. } = decl {
            let kind = if *union { "union" } else { "struct" };
            let _ = writeln!(text, "typedef {kind} {tag} {name};");
        }
    }

    text.push_str("\n/* ------------------------------------------------------------ types */\n\n");
    for decl in &decls {
        match decl {
            Decl::Alias { name, ty } => {
                let _ = writeln!(text, "typedef {};", c_decl(ty, name)?);
            }
            Decl::Enum { name, members } => {
                let _ = writeln!(text, "typedef enum {{");
                for (member, value) in members {
                    let value = expr_c(value).map_err(|e| format!("{name}::{member}: {e}"))?;
                    let _ = writeln!(text, "    {member} = {value},");
                }
                let _ = writeln!(text, "}} {name};\n");
            }
            Decl::Record { name, tag, union, fields, opaque: false, doc } => {
                if !doc.is_empty() {
                    let _ = writeln!(text, "/* {doc} */");
                }
                let kind = if *union { "union" } else { "struct" };
                let _ = writeln!(text, "{kind} {tag} {{");
                for field in fields {
                    if field.anonymous {
                        let type_name = path_name(&field.ty)
                            .ok_or_else(|| format!("{name}.{}: anonymous member needs a named type", field.name))?;
                        let (inner_union, inner) = records
                            .get(&type_name)
                            .ok_or_else(|| format!("{name}.{}: unknown anonymous type {type_name}", field.name))?;
                        let _ = writeln!(text, "    {} {{", if *inner_union { "union" } else { "struct" });
                        for (inner_name, inner_ty) in inner {
                            let _ = writeln!(text, "        {};", c_decl(inner_ty, inner_name)?);
                        }
                        text.push_str("    };\n");
                    } else {
                        let _ = writeln!(text, "    {};", c_decl(&field.ty, &field.name)?);
                    }
                }
                text.push_str("};\n\n");
            }
            _ => {}
        }
    }

    text.push_str("/* ------------------------------------------------------------ globals */\n\n");
    for (_, decl) in &exported {
        if let Decl::Static { text: line } = decl {
            let _ = writeln!(text, "{line}");
        }
    }
    text.push_str("\n/* ------------------------------------------------------------ functions */\n\n");
    for decl in &decls {
        if let Decl::Function { text: line } = decl {
            let _ = writeln!(text, "{line}");
        }
    }
    for (_, decl) in &exported {
        if let Decl::Function { text: line } = decl {
            let _ = writeln!(text, "{line}");
        }
    }
    text.push_str("\n#ifdef __cplusplus\n}\n#endif\n\n#endif /* ELEPHC_ZEND_ABI_H */\n");
    Ok(text)
}

/// Reads and parses a Rust source file with syn, returning a descriptive error string on I/O or
/// syntax failure.
fn parse(path: &Path) -> Result<syn::File, String> {
    let source = fs::read_to_string(path).map_err(|e| format!("read {}: {e}", path.display()))?;
    syn::parse_file(&source).map_err(|e| format!("parse {}: {e}", path.display()))
}

/// The `c:` directives of an item's doc comment, and its first prose line.
fn directives(attrs: &[Attribute]) -> (Vec<String>, String) {
    let mut directives = Vec::new();
    let mut first = String::new();
    for attr in attrs {
        if !attr.path().is_ident("doc") {
            continue;
        }
        if let syn::Meta::NameValue(nv) = &attr.meta {
            if let Expr::Lit(syn::ExprLit { lit: Lit::Str(s), .. }) = &nv.value {
                let line = s.value().trim().to_string();
                if let Some(rest) = line.strip_prefix("c:") {
                    directives.push(rest.trim().to_string());
                } else if first.is_empty() && !line.is_empty() {
                    first = line.replace("*/", "* /");
                }
            }
        }
    }
    (directives, first)
}

/// Returns whether an attribute list contains the named attribute, including the `#[unsafe(name)]`
/// spelling.
fn has_attr(attrs: &[Attribute], name: &str) -> bool {
    attrs.iter().any(|attr| {
        attr.path().is_ident(name)
            || (attr.path().is_ident("unsafe")
                && attr.meta.require_list().map(|l| l.tokens.to_string() == name).unwrap_or(false))
    })
}

/// Returns whether an attribute list carries a `#[repr(C)]`-style attribute (any repr list
/// containing `C`).
fn is_repr_c(attrs: &[Attribute]) -> bool {
    attrs.iter().any(|attr| {
        attr.path().is_ident("repr")
            && attr.meta.require_list().map(|l| l.tokens.to_string().contains('C')).unwrap_or(false)
    })
}

/// Returns an identifier's text with a raw-identifier `r#` prefix removed.
fn ident_text(ident: &syn::Ident) -> String {
    let text = ident.to_string();
    text.strip_prefix("r#").map(str::to_string).unwrap_or(text)
}

/// Collects the type, record, enum and constant declarations of one ABI source file into `decls`,
/// honouring the `c:` doc directives; returns an error string on parse or unsupported-type failure.
fn collect_abi(path: &Path, decls: &mut Vec<Decl>) -> Result<(), String> {
    let file = parse(path)?;
    let enums: Vec<String> = file
        .items
        .iter()
        .filter_map(|item| match item {
            Item::Type(item) if directives(&item.attrs).0.iter().any(|d| d == "enum") => Some(ident_text(&item.ident)),
            _ => None,
        })
        .collect();
    for item in file.items {
        match item {
            Item::Const(item) if path_name(&item.ty).is_some_and(|ty| enums.contains(&ty)) => {
                let owner = path_name(&item.ty).unwrap();
                let entry = decls.iter_mut().find_map(|decl| match decl {
                    Decl::Enum { name, members } if *name == owner => Some(members),
                    _ => None,
                });
                match entry {
                    Some(members) => members.push((ident_text(&item.ident), (*item.expr).clone())),
                    None => return Err(format!("{}: enum member declared before its enum", ident_text(&item.ident))),
                }
            }
            Item::Type(item) if enums.contains(&ident_text(&item.ident)) => {
                decls.push(Decl::Enum { name: ident_text(&item.ident), members: Vec::new() });
            }
            Item::Const(item) => {
                let (_, doc) = directives(&item.attrs);
                decls.push(Decl::Const {
                    name: ident_text(&item.ident),
                    ty: (*item.ty).clone(),
                    value: (*item.expr).clone(),
                    doc,
                });
            }
            Item::Type(item) => {
                decls.push(Decl::Alias { name: ident_text(&item.ident), ty: (*item.ty).clone() });
            }
            Item::Struct(item) if is_repr_c(&item.attrs) => {
                let (dirs, doc) = directives(&item.attrs);
                let name = ident_text(&item.ident);
                let fields = match &item.fields {
                    Fields::Named(named) => named
                        .named
                        .iter()
                        .map(|f| Field {
                            name: ident_text(f.ident.as_ref().unwrap()),
                            ty: f.ty.clone(),
                            anonymous: directives(&f.attrs).0.iter().any(|d| d == "anonymous"),
                        })
                        .collect(),
                    _ => Vec::new(),
                };
                decls.extend(record(name, &dirs, false, fields, doc));
            }
            Item::Union(item) if is_repr_c(&item.attrs) => {
                let (dirs, doc) = directives(&item.attrs);
                let name = ident_text(&item.ident);
                let fields = item
                    .fields
                    .named
                    .iter()
                    .map(|f| Field {
                        name: ident_text(f.ident.as_ref().unwrap()),
                        ty: f.ty.clone(),
                        anonymous: directives(&f.attrs).0.iter().any(|d| d == "anonymous"),
                    })
                    .collect();
                decls.extend(record(name, &dirs, true, fields, doc));
            }
            Item::ForeignMod(block) => {
                for foreign in block.items {
                    if let ForeignItem::Fn(function) = foreign {
                        let (dirs, _) = directives(&function.attrs);
                        if dirs.iter().any(|d| d == "hidden") {
                            continue;
                        }
                        decls.push(Decl::Function { text: prototype(&function.sig)? });
                    }
                }
            }
            _ => {}
        }
    }
    Ok(())
}

/// Builds a record (struct or union) declaration, or registers a `system` spelling override and
/// returns None when the directive says the type comes from a system header.
fn record(name: String, dirs: &[String], union: bool, fields: Vec<Field>, doc: String) -> Option<Decl> {
    if let Some(spelling) = dirs.iter().find_map(|d| d.strip_prefix("system ")) {
        SYSTEM.with(|system| system.borrow_mut().insert(name, spelling.trim().to_string()));
        return None;
    }
    let tag = dirs
        .iter()
        .find_map(|d| d.strip_prefix("tag ").map(|t| t.trim().to_string()))
        .unwrap_or_else(|| format!("_{name}"));
    let opaque = dirs.iter().any(|d| d == "opaque");
    Some(Decl::Record { name, tag, union, fields, opaque, doc })
}

/// Recursively walks a source directory in sorted order, parsing each `.rs` file and gathering its
/// exported C items into `out`.
fn collect_exports(dir: &Path, out: &mut Vec<(String, Decl)>) -> Result<(), String> {
    let mut entries: Vec<_> = fs::read_dir(dir)
        .map_err(|e| format!("read {}: {e}", dir.display()))?
        .filter_map(|entry| entry.ok().map(|entry| entry.path()))
        .collect();
    entries.sort();
    for path in entries {
        if path.is_dir() {
            collect_exports(&path, out)?;
        } else if path.extension().is_some_and(|ext| ext == "rs") {
            let file = parse(&path)?;
            collect_items(&file.items, out)?;
        }
    }
    Ok(())
}

/// Scans items for `#[no_mangle]` functions and statics (skipping those marked `c: hidden`) and
/// pushes their C prototypes or declarations into `out`; errors on unsupported signatures.
fn collect_items(items: &[Item], out: &mut Vec<(String, Decl)>) -> Result<(), String> {
    for item in items {
        match item {
            Item::Fn(function) if has_attr(&function.attrs, "no_mangle") => {
                let (dirs, _) = directives(&function.attrs);
                if dirs.iter().any(|d| d == "hidden") {
                    continue;
                }
                out.push((function.sig.ident.to_string(), Decl::Function { text: prototype(&function.sig)? }));
            }
            Item::Static(item) if has_attr(&item.attrs, "no_mangle") => {
                let (dirs, _) = directives(&item.attrs);
                if dirs.iter().any(|d| d == "hidden") {
                    continue;
                }
                let name = ident_text(&item.ident);
                let mutable = !matches!(item.mutability, syn::StaticMutability::None);
                let decl = c_decl(&item.ty, &name)?;
                let text = if mutable { format!("extern {decl};") } else { format!("extern {};", const_object(&decl)) };
                out.push((name, Decl::Static { text }));
            }
            Item::Mod(module) => {
                if let Some((_, items)) = &module.content {
                    collect_items(items, out)?;
                }
            }
            _ => {}
        }
    }
    Ok(())
}

/// A non-`mut` static is immutable data: C sees it `const`.
fn const_object(decl: &str) -> String {
    if decl.contains('*') || decl.contains('[') {
        decl.to_string()
    } else {
        format!("const {decl}")
    }
}

/// Renders a Rust function signature as a C prototype string, failing on unsupported parameter
/// patterns or types.
fn prototype(sig: &syn::Signature) -> Result<String, String> {
    let name = ident_text(&sig.ident);
    let mut params = Vec::new();
    for input in &sig.inputs {
        match input {
            FnArg::Typed(typed) => {
                let param = match &*typed.pat {
                    Pat::Ident(ident) => ident_text(&ident.ident),
                    Pat::Wild(_) => String::new(),
                    _ => return Err(format!("{name}: unsupported parameter pattern")),
                };
                let param = param.trim_start_matches('_').to_string();
                params.push(c_decl(&typed.ty, &param)?);
            }
            FnArg::Receiver(_) => return Err(format!("{name}: methods cannot be exported")),
        }
    }
    if sig.variadic.is_some() {
        params.push("...".to_string());
    } else if params.is_empty() {
        params.push("void".to_string());
    }
    let (noreturn, ret) = match &sig.output {
        ReturnType::Default => (false, None),
        ReturnType::Type(_, ty) => match &**ty {
            Type::Never(_) => (true, None),
            ty => (false, Some(ty.clone())),
        },
    };
    let declarator = format!("{name}({})", params.join(", "));
    let text = match ret {
        Some(ty) => c_decl(&ty, &declarator)?,
        None => format!("void {declarator}"),
    };
    Ok(if noreturn { format!("__attribute__((noreturn)) {text};") } else { format!("{text};") })
}

/// The C name of a Rust primitive or ABI type.
fn base_name(path: &syn::TypePath) -> Result<String, String> {
    let last = path.path.segments.last().ok_or("empty type path")?;
    let name = ident_text(&last.ident);
    if let Some(spelling) = SYSTEM.with(|system| system.borrow().get(&name).cloned()) {
        return Ok(spelling);
    }
    Ok(match name.as_str() {
        "c_char" => "char",
        "c_schar" | "i8" => "int8_t",
        "c_uchar" | "u8" => "uint8_t",
        "c_short" | "i16" => "int16_t",
        "c_ushort" | "u16" => "uint16_t",
        "c_int" => "int",
        "c_uint" => "unsigned int",
        "i32" => "int32_t",
        "u32" => "uint32_t",
        "c_long" => "long",
        "c_ulong" => "unsigned long",
        "i64" | "c_longlong" => "int64_t",
        "u64" | "c_ulonglong" => "uint64_t",
        "usize" | "size_t" => "size_t",
        "isize" | "ssize_t" => "ssize_t",
        "f64" | "c_double" => "double",
        "f32" | "c_float" => "float",
        "bool" => "bool",
        "c_void" => "void",
        other => other,
    }
    .to_string())
}

/// Returns the last path segment of a path type as text, or None for non-path types.
fn path_name(ty: &Type) -> Option<String> {
    match ty {
        Type::Path(path) => path.path.segments.last().map(|s| ident_text(&s.ident)),
        _ => None,
    }
}

/// The function type inside `Option<unsafe extern "C" fn(..)>`, if `ty` is one.
fn option_fn(ty: &Type) -> Option<&syn::TypeBareFn> {
    let Type::Path(path) = ty else { return None };
    let last = path.path.segments.last()?;
    if last.ident != "Option" {
        return None;
    }
    let PathArguments::AngleBracketed(args) = &last.arguments else { return None };
    match args.args.first()? {
        GenericArgument::Type(Type::BareFn(function)) => Some(function),
        _ => None,
    }
}

/// Renders `ty` declaring `inner` (a name or an inner declarator).
fn c_decl(ty: &Type, inner: &str) -> Result<String, String> {
    let space = |inner: &str| if inner.is_empty() { String::new() } else { format!(" {inner}") };
    if let Some(function) = option_fn(ty) {
        return fn_decl(function, inner);
    }
    match ty {
        Type::BareFn(function) => fn_decl(function, inner),
        Type::Path(path) => Ok(format!("{}{}", base_name(path)?, space(inner))),
        Type::Ptr(pointer) => {
            let inner = format!("*{inner}");
            if pointer.const_token.is_some() {
                if let Type::Path(path) = &*pointer.elem {
                    return Ok(format!("const {} {inner}", base_name(path)?));
                }
            }
            c_decl(&pointer.elem, &inner)
        }
        Type::Array(array) => {
            let len = expr_c(&array.len)?;
            let inner = if inner.starts_with('*') { format!("({inner})") } else { inner.to_string() };
            c_decl(&array.elem, &format!("{inner}[{len}]"))
        }
        Type::Tuple(tuple) if tuple.elems.is_empty() => Ok(format!("void{}", space(inner))),
        Type::Paren(paren) => c_decl(&paren.elem, inner),
        other => Err(format!("unsupported type {other:?} for {inner}")),
    }
}

/// Renders a bare `fn` pointer type as a C function-pointer declarator wrapping `inner`, including
/// variadic `...`.
fn fn_decl(function: &syn::TypeBareFn, inner: &str) -> Result<String, String> {
    let mut params = Vec::new();
    for input in &function.inputs {
        let name = input
            .name
            .as_ref()
            .map(|(ident, _)| ident_text(ident).trim_start_matches('_').to_string())
            .unwrap_or_default();
        params.push(c_decl(&input.ty, &name)?);
    }
    if function.variadic.is_some() {
        params.push("...".to_string());
    } else if params.is_empty() {
        params.push("void".to_string());
    }
    let declarator = format!("(*{inner})({})", params.join(", "));
    match &function.output {
        ReturnType::Default => Ok(format!("void {declarator}")),
        ReturnType::Type(_, ty) => match &**ty {
            Type::Never(_) => Ok(format!("void {declarator}")),
            ty => c_decl(ty, &declarator),
        },
    }
}

/// A constant expression in C syntax.
fn expr_c(expr: &Expr) -> Result<String, String> {
    expr_c_signed(expr, true)
}

/// Translates a Rust constant expression to C source text, using the signedness flag to pick
/// integer literal suffixes; errors on unsupported expressions.
fn expr_c_signed(expr: &Expr, signed: bool) -> Result<String, String> {
    Ok(match expr {
        Expr::Lit(lit) => match &lit.lit {
            Lit::Int(int) => int_literal(int.base10_digits(), &int.to_string(), signed),
            Lit::Float(float) => float.base10_digits().to_string(),
            Lit::Str(s) => c_string(&s.value()),
            Lit::Bool(b) => if b.value { "1" } else { "0" }.to_string(),
            Lit::Char(c) => format!("'{}'", c.value()),
            other => return Err(format!("unsupported literal {other:?}")),
        },
        Expr::Path(path) => ident_text(&path.path.segments.last().unwrap().ident),
        Expr::Paren(paren) => format!("({})", expr_c_signed(&paren.expr, signed)?),
        Expr::Group(group) => expr_c_signed(&group.expr, signed)?,
        Expr::Unary(unary) => match unary.op {
            UnOp::Neg(_) => format!("-{}", expr_c_signed(&unary.expr, signed)?),
            UnOp::Not(_) => format!("~{}", expr_c_signed(&unary.expr, signed)?),
            _ => return Err("unsupported unary operator".into()),
        },
        Expr::Binary(binary) => {
            let op = match binary.op {
                BinOp::Add(_) => "+",
                BinOp::Sub(_) => "-",
                BinOp::Mul(_) => "*",
                BinOp::Div(_) => "/",
                BinOp::Rem(_) => "%",
                BinOp::BitOr(_) => "|",
                BinOp::BitAnd(_) => "&",
                BinOp::BitXor(_) => "^",
                BinOp::Shl(_) => "<<",
                BinOp::Shr(_) => ">>",
                _ => return Err("unsupported binary operator".into()),
            };
            format!("({} {op} {})", expr_c_signed(&binary.left, signed)?, expr_c_signed(&binary.right, signed)?)
        }
        Expr::Cast(cast) => format!("(({}){})", c_decl(&cast.ty, "")?, expr_c_signed(&cast.expr, signed)?),
        other => return Err(format!("unsupported constant expression {other:?}")),
    })
}

/// An integer literal without Rust's suffix or separators, hex kept as hex.
fn int_literal(decimal: &str, written: &str, signed: bool) -> String {
    let written = written.replace('_', "");
    let digits = written.trim_end_matches(|c: char| c.is_ascii_alphabetic() && !c.is_ascii_hexdigit());
    let digits = ["i8", "u8", "i16", "u16", "i32", "u32", "i64", "u64", "usize", "isize"]
        .iter()
        .find_map(|suffix| written.strip_suffix(suffix))
        .unwrap_or(digits);
    let value: u128 = decimal.parse().unwrap_or(0);
    let suffix = match (value > u32::MAX as u128, value > i32::MAX as u128, signed) {
        (true, _, true) => "LL",
        (true, _, false) => "ULL",
        (false, true, true) => "LL",
        (false, true, false) => "u",
        _ => "",
    };
    format!("{digits}{suffix}")
}

/// Quotes a string as a C string literal, escaping quotes, backslashes, newlines and non-printable
/// bytes as octal.
fn c_string(value: &str) -> String {
    let mut out = String::from("\"");
    for byte in value.bytes() {
        match byte {
            b'"' => out.push_str("\\\""),
            b'\\' => out.push_str("\\\\"),
            b'\n' => out.push_str("\\n"),
            0x20..=0x7e => out.push(byte as char),
            other => {
                let _ = write!(out, "\\{other:03o}");
            }
        }
    }
    out.push('"');
    out
}

/// A constant's `#define` body. Integer constants stay bare numbers or
/// operator expressions, so `#if PHP_VERSION_ID >= ...` keeps working.
fn const_value(name: &str, ty: &Type, value: &Expr) -> Result<String, String> {
    let signed = !matches!(path_name(ty).as_deref(), Some("u8" | "u16" | "u32" | "u64" | "usize" | "zend_ulong"));
    let text = expr_c_signed(value, signed).map_err(|e| format!("{name}: {e}"))?;
    let is_str = matches!(ty, Type::Reference(_));
    Ok(if is_str || matches!(value, Expr::Lit(_)) { text } else { format!("({text})") })
}
