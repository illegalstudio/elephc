    emit_st(emitter, "xor r10d, r10d");
    emitter.label("__rt_strip_tags_tag_find_norm_x86");
    emit_st(emitter, "cmp r8, rcx");
    emit_st(emitter, "jae __rt_strip_tags_tag_find_end_x86");
