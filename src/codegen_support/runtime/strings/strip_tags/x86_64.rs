//! Purpose:
//! Linux x86_64 `__rt_strip_tags` state machine for PHP 8.5 `strip_tags()`.
//!
//! Called from:
//! - `super::emit_strip_tags()` when the target is x86_64.
//!
//! Key details:
//! - ABI: `rdi`/`rsi` = subject pointer/length, `rdx`/`rcx` = allow pointer/length.
//! - Result: `rax`/`rdx` = stripped pointer/length, published through
//!   `__rt_concat_publish`.
//! - Zero allow length is treated as no allow-list.

use crate::codegen_support::emit::Emitter;

use super::emit_st;

/// Emits the Linux x86_64 `__rt_strip_tags` helper.
pub(super) fn emit_strip_tags_linux_x86_64(emitter: &mut Emitter) {
    emitter.blank();
    emitter.comment("--- runtime: strip_tags ---");
    emitter.label_global("__rt_strip_tags");

    emit_st(emitter, "push rbp");
    emit_st(emitter, "mov rbp, rsp");
    emit_st(emitter, "sub rsp, 208");
    emit_st(emitter, "mov QWORD PTR [rbp - 152], rbx");
    emit_st(emitter, "mov QWORD PTR [rbp - 160], r12");
    emit_st(emitter, "mov QWORD PTR [rbp - 168], r13");
    emit_st(emitter, "mov QWORD PTR [rbp - 176], r14");
    emit_st(emitter, "mov QWORD PTR [rbp - 184], r15");
    emit_st(emitter, "mov QWORD PTR [rbp - 8], rdi");
    emit_st(emitter, "mov QWORD PTR [rbp - 16], rsi");
    emit_st(emitter, "mov QWORD PTR [rbp - 24], rdx");
    emit_st(emitter, "mov QWORD PTR [rbp - 32], rcx");

    emitter.comment("-- reserve output, and allow/tag/norm scratch when an allow-list is present --");
    emit_st(emitter, "mov rax, rsi");
    emit_st(emitter, "test rcx, rcx");
    emit_st(emitter, "jz __rt_strip_tags_reserve_x86");
    emit_st(emitter, "mov rdx, rsi");
    emit_st(emitter, "shl rdx, 1");
    emit_st(emitter, "jo __rt_strip_tags_overflow_x86");
    emit_st(emitter, "add rdx, rsi");
    emit_st(emitter, "jo __rt_strip_tags_overflow_x86");
    emit_st(emitter, "add rdx, rcx");
    emit_st(emitter, "jo __rt_strip_tags_overflow_x86");
    emit_st(emitter, "add rdx, 4");
    emit_st(emitter, "jo __rt_strip_tags_overflow_x86");
    emit_st(emitter, "mov rax, rdx");
    emitter.label("__rt_strip_tags_reserve_x86");
    emit_st(emitter, "call __rt_concat_reserve");
    emit_st(emitter, "mov QWORD PTR [rbp - 40], rax");
    emit_st(emitter, "mov QWORD PTR [rbp - 48], rax");
    emit_st(emitter, "xor eax, eax");
    emit_st(emitter, "mov QWORD PTR [rbp - 56], rax");
    emit_st(emitter, "mov QWORD PTR [rbp - 64], rax");
    emit_st(emitter, "mov QWORD PTR [rbp - 72], rax");
    emit_st(emitter, "mov QWORD PTR [rbp - 80], rax");
    emit_st(emitter, "mov QWORD PTR [rbp - 88], rax");
    emit_st(emitter, "cmp QWORD PTR [rbp - 32], 0");
    emit_st(emitter, "je __rt_strip_tags_init_x86");

    emitter.comment("-- partition the reservation: out | allow_lc | tag | norm --");
    emit_st(emitter, "mov rax, QWORD PTR [rbp - 40]");
    emit_st(emitter, "add rax, QWORD PTR [rbp - 16]");
    emit_st(emitter, "mov QWORD PTR [rbp - 72], rax");
    emit_st(emitter, "mov rdx, QWORD PTR [rbp - 32]");
    emit_st(emitter, "mov QWORD PTR [rbp - 80], rdx");
    emit_st(emitter, "add rax, rdx");
    emit_st(emitter, "mov QWORD PTR [rbp - 56], rax");
    emit_st(emitter, "mov rdx, QWORD PTR [rbp - 16]");
    emit_st(emitter, "add rdx, 2");
    emit_st(emitter, "add rax, rdx");
    emit_st(emitter, "mov QWORD PTR [rbp - 88], rax");
    emit_st(emitter, "mov rsi, QWORD PTR [rbp - 24]");
    emit_st(emitter, "mov rdi, QWORD PTR [rbp - 72]");
    emit_st(emitter, "mov rcx, QWORD PTR [rbp - 32]");
    emit_st(emitter, "xor r8d, r8d");
    emitter.label("__rt_strip_tags_lc_allow_x86");
    emit_st(emitter, "cmp r8, rcx");
    emit_st(emitter, "jae __rt_strip_tags_init_x86");
    emit_st(emitter, "movzx eax, BYTE PTR [rsi + r8]");
    emit_st(emitter, "cmp al, 65");
    emit_st(emitter, "jb __rt_strip_tags_lc_store_x86");
    emit_st(emitter, "cmp al, 90");
    emit_st(emitter, "ja __rt_strip_tags_lc_store_x86");
    emit_st(emitter, "or al, 32");
    emitter.label("__rt_strip_tags_lc_store_x86");
    emit_st(emitter, "mov BYTE PTR [rdi + r8], al");
    emit_st(emitter, "add r8, 1");
    emit_st(emitter, "jmp __rt_strip_tags_lc_allow_x86");

    emitter.label("__rt_strip_tags_init_x86");
    emit_st(emitter, "xor eax, eax");
    emit_st(emitter, "mov QWORD PTR [rbp - 96], rax");
    emit_st(emitter, "mov QWORD PTR [rbp - 104], rax");
    emit_st(emitter, "mov QWORD PTR [rbp - 112], rax");
    emit_st(emitter, "mov QWORD PTR [rbp - 120], rax");
    emit_st(emitter, "mov QWORD PTR [rbp - 128], rax");
    emit_st(emitter, "mov QWORD PTR [rbp - 136], rax");
    emit_st(emitter, "mov QWORD PTR [rbp - 144], rax");
    emit_st(emitter, "mov r12, QWORD PTR [rbp - 8]");
    emit_st(emitter, "mov r13, QWORD PTR [rbp - 16]");

    emitter.label("__rt_strip_tags_loop_x86");
    emit_st(emitter, "mov r14, QWORD PTR [rbp - 96]");
    emit_st(emitter, "cmp r14, r13");
    emit_st(emitter, "jae __rt_strip_tags_done_x86");
    emit_st(emitter, "movzx eax, BYTE PTR [r12 + r14]");
    emit_st(emitter, "mov r15d, eax");
    emit_st(emitter, "mov rax, QWORD PTR [rbp - 104]");
    emit_st(emitter, "cmp rax, 0");
    emit_st(emitter, "je __rt_strip_tags_s0_x86");
    emit_st(emitter, "cmp rax, 1");
    emit_st(emitter, "je __rt_strip_tags_s1_x86");
    emit_st(emitter, "cmp rax, 2");
    emit_st(emitter, "je __rt_strip_tags_s2_x86");
    emit_st(emitter, "cmp rax, 3");
    emit_st(emitter, "je __rt_strip_tags_s3_x86");
    emit_st(emitter, "jmp __rt_strip_tags_s4_x86");

    emit_state0_x86(emitter);
    emit_state1_x86(emitter);
    emit_state2_x86(emitter);
    emit_state3_x86(emitter);
    emit_state4_x86(emitter);
    emit_helpers_x86(emitter);

    emitter.label("__rt_strip_tags_done_x86");
    emit_st(emitter, "mov rax, QWORD PTR [rbp - 40]");
    emit_st(emitter, "mov rdx, QWORD PTR [rbp - 48]");
    emit_st(emitter, "sub rdx, rax");
    emit_st(emitter, "call __rt_concat_publish");
    emit_st(emitter, "mov rbx, QWORD PTR [rbp - 152]");
    emit_st(emitter, "mov r12, QWORD PTR [rbp - 160]");
    emit_st(emitter, "mov r13, QWORD PTR [rbp - 168]");
    emit_st(emitter, "mov r14, QWORD PTR [rbp - 176]");
    emit_st(emitter, "mov r15, QWORD PTR [rbp - 184]");
    emit_st(emitter, "add rsp, 208");
    emit_st(emitter, "pop rbp");
    emit_st(emitter, "ret");

    emitter.label("__rt_strip_tags_overflow_x86");
    emit_st(emitter, "jmp __rt_alloc_overflow");
}

/// Emits output-state handling (state 0).
fn emit_state0_x86(emitter: &mut Emitter) {
    emitter.comment("-- state 0: copy bytes until a real tag opener --");
    emitter.label("__rt_strip_tags_s0_x86");
    emit_st(emitter, "test r15b, r15b");
    emit_st(emitter, "jz __rt_strip_tags_advance_x86");
    emit_st(emitter, "cmp r15b, 60");
    emit_st(emitter, "jne __rt_strip_tags_s0_gt_x86");
    emit_st(emitter, "cmp QWORD PTR [rbp - 112], 0");
    emit_st(emitter, "jne __rt_strip_tags_advance_x86");
    emit_st(emitter, "call __rt_strip_tags_next_x86");
    emit_st(emitter, "call __rt_strip_tags_isspace_x86");
    emit_st(emitter, "test eax, eax");
    emit_st(emitter, "jz __rt_strip_tags_s0_open_x86");
    emit_st(emitter, "mov eax, 60");
    emit_st(emitter, "call __rt_strip_tags_putc_x86");
    emit_st(emitter, "jmp __rt_strip_tags_advance_x86");
    emitter.label("__rt_strip_tags_s0_open_x86");
    emit_st(emitter, "mov QWORD PTR [rbp - 136], 60");
    emit_st(emitter, "mov QWORD PTR [rbp - 104], 1");
    emit_st(emitter, "cmp QWORD PTR [rbp - 80], 0");
    emit_st(emitter, "je __rt_strip_tags_s0_open_adv_x86");
    emit_st(emitter, "mov QWORD PTR [rbp - 64], 0");
    emit_st(emitter, "mov eax, 60");
    emit_st(emitter, "call __rt_strip_tags_collect_x86");
    emitter.label("__rt_strip_tags_s0_open_adv_x86");
    emit_st(emitter, "add QWORD PTR [rbp - 96], 1");
    emit_st(emitter, "jmp __rt_strip_tags_loop_x86");
    emitter.label("__rt_strip_tags_s0_gt_x86");
    emit_st(emitter, "cmp r15b, 62");
    emit_st(emitter, "jne __rt_strip_tags_s0_copy_x86");
    emit_st(emitter, "cmp QWORD PTR [rbp - 120], 0");
    emit_st(emitter, "jle __rt_strip_tags_s0_gt_q_x86");
    emit_st(emitter, "sub QWORD PTR [rbp - 120], 1");
    emit_st(emitter, "jmp __rt_strip_tags_advance_x86");
    emitter.label("__rt_strip_tags_s0_gt_q_x86");
    emit_st(emitter, "cmp QWORD PTR [rbp - 112], 0");
    emit_st(emitter, "jne __rt_strip_tags_advance_x86");
    emitter.label("__rt_strip_tags_s0_copy_x86");
    emit_st(emitter, "mov eax, r15d");
    emit_st(emitter, "call __rt_strip_tags_putc_x86");
    emit_st(emitter, "jmp __rt_strip_tags_advance_x86");
}

